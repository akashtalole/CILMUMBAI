export const STRINGS: Record<Lang, Strings> = { mr, hi, en };
export const LANG_NAMES: Record<Lang, string> = { mr: "मराठी", hi: "हिंदी", en: "English" };
export const LOCALES: Record<Lang, string> = { mr: "mr-IN", hi: "hi-IN", en: "en-IN" };

export function formatDate(iso: string, lang: Lang): string {
  const date = new Date(`${iso}T00:00:00`);
  if (Number.isNaN(date.getTime())) return iso;
  return date.toLocaleDateString(LOCALES[lang], { day: "numeric", month: "long", year: "numeric", numberingSystem: "latn" });
}

export function formatRupees(amount: number, lang: Lang): string {
  const exact = "₹" + amount.toLocaleString("en-IN");
  const unit = { mr: ["कोटी", "लाख"], hi: ["करोड़", "लाख"], en: ["crore", "lakh"] }[lang];
  const short =
    amount >= 1e7 ? `${+(amount / 1e7).toFixed(2)} ${unit[0]}` : amount >= 1e5 ? `${+(amount / 1e5).toFixed(2)} ${unit[1]}` : "";
  return short ? `${exact} (₹${short})` : exact;
}
